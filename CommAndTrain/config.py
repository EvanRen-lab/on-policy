#!/usr/bin/env python
"""
DFL Configuration Management
"""
import json
import os
import numpy as np
from dataclasses import dataclass, field
from typing import List, Optional
import torch


@dataclass
class DFLConfig:
    """DFL configuration class (contains all parameters for training, data, wireless communication, etc.)"""

    # -------------------- Basic experiment configuration --------------------
    experiment_name: str = "dfl_baseline"
    seed: int = 42
    device: str = "cuda" if torch.cuda.is_available() else "cpu"
    base_output_dir: str = "/data/8T/zhouh/outages/results"  # Base directory for all results

    # -------------------- Strategy selection --------------------
    strategies_to_compare: List[str] = field(default_factory=lambda: ['mappo', 'alternating', 'avg', 'random'])

    # -------------------- Allocator-specific parameters --------------------
    alternating_iterations: int = 5           # Number of alternating optimization iterations
    random_iterations: int = 100              # Number of random search iterations
    power_optimization_method: str = "SLSQP"  # Power optimization method
    record_allocation_time: bool = True       # Whether to record allocation solving time
    max_allocation_time: float = 30.0         # Allocation solving timeout threshold (seconds)

    # -------------------- Terminal configuration --------------------
    num_agents: int = 5
    weights: Optional[List[float]] = None      # Terminal importance weights, randomly generated by default
    coefficients: Optional[List[float]] = None # Self-interference coefficients, randomly generated by default

    # -------------------- Wireless communication parameters --------------------
    num_channels: int = 8                     # Number of channels
    max_power: float = 0.2                     # Maximum transmit power (W)
    bandwidth: float = 1e6                      # Bandwidth (Hz)
    noise_dbm: float = -174                      # Noise power (dBm)
    sinr_threshold_db: float = 5.0              # SINR threshold (dB)
    distance_scale: float = 1000.0                # Path loss reference distance (m)
    pathloss_a: float = 128.1                     # Path loss constant A
    pathloss_b: float = 37.6                      # Path loss exponent B

    # Mobility configuration
    mobility_enabled: bool = True
    deployment_radius: float = 200.0               # Deployment radius (m)
    max_speed: float = 5.0                         # Maximum moving speed (m/s)

    # -------------------- Dataset configuration --------------------
    dataset_name: str = "cifar10"
    data_dir: str = "/data/8T/zhouh/outages/data"
    train_size: int = 50000
    test_size: int = 10000

    # Data partitioning configuration
    data_distribution: str = "non_iid"          # "iid" or "non_iid"
    non_iid_degree: float = 0.8                 # Between 0 and 1, degree of non-IID
    class_imbalance: bool = True                 # Whether to introduce class imbalance

    # -------------------- Model configuration --------------------
    model_name: str = "resnet18"
    num_classes: int = 10
    pretrained: bool = False

    # -------------------- Training configuration --------------------
    batch_size: int = 128
    learning_rate: float = 0.01
    momentum: float = 0.9
    weight_decay: float = 1e-4
    local_epochs: int = 5                          # Number of local training epochs
    communication_rounds: int = 10                # Number of global communication rounds

    # Optimizer configuration
    optimizer: str = "sgd"                         # "sgd" or "adam"
    lr_scheduler: str = "step"                     # "step", "cosine", "none"
    lr_decay_step: int = 30
    lr_decay_gamma: float = 0.1

    # -------------------- Communication aggregation configuration --------------------
    communication_mode: str = "thread"              # "sequential", "thread", "process"
    max_workers: int = 5
    communication_interval: int = 1                 # Communicate every N rounds (usually 1)
    aggregation_method: str = "weighted"            # "average" or "weighted"
    mixing_factor: float = 0.7                      # FedAvg parameter

    # -------------------- Evaluation and saving configuration --------------------
    eval_frequency: int = 1                         # Evaluate every N rounds
    save_frequency: int = 400                        # Save model every N rounds

    # -------------------- MAPPO configuration --------------------
    use_mappo: bool = True
    mappo_config_path: str = "/data/8T/zhouh/outages/model/dfl_ep1_64t_0315_1439/wandb/wandb/latest-run/files/config.yaml"
    mappo_model_path: str = "/data/8T/zhouh/outages/model/dfl_ep1_64t_0315_1439/models/actor.pt"

    # -------------------- Random generation parameter control --------------------
    weights_alpha: float = 2.0                     # Dirichlet parameter, larger value gives more uniform weight distribution
    coeff_min: float = 1e-9                        # Minimum self-interference coefficient
    coeff_max: float = 1e-8                        # Maximum self-interference coefficient

    def __post_init__(self):
        """Post-initialization processing, including random generation of weights and coefficients if not provided."""
        if self.seed is not None:
            np.random.seed(self.seed)

        # If terminal weights are not provided, generate randomly
        if self.weights is None:
            self.weights = np.random.dirichlet([self.weights_alpha] * self.num_agents).tolist()
        else:
            # Ensure weight list length matches number of terminals
            if len(self.weights) != self.num_agents:
                if len(self.weights) > self.num_agents:
                    self.weights = self.weights[:self.num_agents]
                else:
                    last_val = self.weights[-1] if self.weights else 1.0
                    self.weights.extend([last_val] * (self.num_agents - len(self.weights)))
            # Normalize weights
            total = sum(self.weights)
            if abs(total - 1.0) > 1e-6:
                self.weights = [w / total for w in self.weights]

        # If self-interference coefficients are not provided, generate randomly
        if self.coefficients is None:
            self.coefficients = np.random.uniform(self.coeff_min, self.coeff_max, self.num_agents).tolist()
        else:
            if len(self.coefficients) != self.num_agents:
                if len(self.coefficients) > self.num_agents:
                    self.coefficients = self.coefficients[:self.num_agents]
                else:
                    last_val = self.coefficients[-1] if self.coefficients else self.coeff_min
                    self.coefficients.extend([last_val] * (self.num_agents - len(self.coefficients)))

        # Compute max_power_dbm (for convenience)
        self.max_power_dbm = 10 * np.log10(self.max_power * 1000)

        # Create base output directory
        os.makedirs(self.base_output_dir, exist_ok=True)


def get_default_config():
    """Get default configuration."""
    return DFLConfig()